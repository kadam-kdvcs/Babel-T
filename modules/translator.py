"""翻译模块（阶段 1 占位实现）。

本阶段不调用任何外部翻译 API，只生成占位译文，用于验证「段落 → 译文」
数据流是否贯通。未来阶段（阶段 2）接入真实翻译 API：
保持函数签名不变，仅替换内部实现。
"""


def translate_paragraphs(paragraphs: list[str]) -> list[str]:
    """把阿语段落列表翻译为一一对应的译文列表。

    作用：翻译流水线的入口。阶段 1 不发起任何网络请求，仅对每个输入段落
          生成一条形如「（占位译文·第N段）待接入翻译 API」的占位字符串，
          用于打通「段落 → 译文」数据流，支撑前端展示与流水线联调。

    输入：paragraphs —— list[str]，阿语段落列表，每个元素是一段待翻译的文本，
          允许为空列表。

    输出：list[str] —— 与输入同长度、同顺序的译文列表；
          空输入返回 []（不报错，不产生任何译文）。

    未来接口约定（阶段 2 不变）：输入段落列表，返回一一对应的译文列表，
    函数签名保持 translate_paragraphs(paragraphs: list[str]) -> list[str]
    不变；阶段 2 仅把内部实现替换为真实翻译 API 调用（如批量请求、
    失败重试、超时处理），所有调用方无需改动。
    """
    # 用列表推导式按段落数生成占位译文，段号从 1 开始
    return [f"（占位译文·第{i + 1}段）待接入翻译 API" for i in range(len(paragraphs))]
